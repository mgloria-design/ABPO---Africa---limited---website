<script>
// Mobile Navigation Menu Toggle
const navToggle = document.getElementById("navToggle");
const navLinks = document.getElementById("navLinks");

if (navToggle && navLinks) {
  navToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("active");
    navToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
  });
}

if (navLinks) {
  navLinks.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      if (window.innerWidth <= 860) {
        navLinks.classList.remove("active");
        if (navToggle) navToggle.setAttribute("aria-expanded", "false");
      }
    });
  });
}

// Show selected file name for CV upload
const cvInput = document.getElementById("cv");
const cvFileName = document.getElementById("cvFileName");
if (cvInput && cvFileName) {
  cvInput.addEventListener("change", () => {
    cvFileName.textContent = cvInput.files.length ? cvInput.files[0].name : "No file selected";
  });
}

// Apply form submit handling
const applyForm = document.getElementById("applyForm");
if (applyForm) {
  applyForm.addEventListener("submit", async (e) => {
    e.preventDefault();

    const btn = document.getElementById("applySubmitBtn");
    const btnText = document.getElementById("applyBtnText");
    const resp = document.getElementById("applyFormResponse");

    if (!applyForm.checkValidity()) {
      applyForm.reportValidity();
      return;
    }

    btn.disabled = true;
    if (btnText) btnText.textContent = "Submitting...";
    resp.style.display = "none";

    try {
      const formData = new FormData(applyForm);
      const res = await fetch(applyForm.action, { method: "POST", body: formData });
      const text = await res.text();
      resp.style.display = "block";
      if (res.ok) {
        resp.className = "form-response success";
        resp.textContent = text || "Your application has been submitted successfully.";
        applyForm.reset();
        if (cvFileName) cvFileName.textContent = "No file selected";
      } else {
        resp.className = "form-response error";
        resp.textContent = text || "Something went wrong. Please try again.";
      }
    } catch (err) {
      resp.style.display = "block";
      resp.className = "form-response error";
      resp.textContent = "Network error. Please try again or email us directly at info@abpoafrica.com";
    } finally {
      btn.disabled = false;
      if (btnText) btnText.textContent = "Submit Application";
    }
  });
}

</script>

