const navbar = document.getElementById("navbar");

window.addEventListener("scroll", () => {
  navbar.classList.toggle("scrolled", window.scrollY > 50);
});

// Mobile Navigation Menu Toggle
const navToggle = document.getElementById("navToggle");
const navLinks = document.getElementById("navLinks");
const mobileCta = document.querySelector(".mobile-cta");

if (navToggle && navLinks) {
  navToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("active");
    navToggle.classList.toggle("active", isOpen);
    navToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
    if (mobileCta) mobileCta.style.display = isOpen ? "block" : "none";
  });
}

// Close mobile menu when a link is clicked
if (navLinks) {
  navLinks.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      if (window.innerWidth <= 900) {
        navLinks.classList.remove("active");
        if (navToggle) {
          navToggle.classList.remove("active");
          navToggle.setAttribute("aria-expanded", "false");
        }
        if (mobileCta) mobileCta.style.display = "none";
      }
    });
  });
}

// Mobile Dropdown Click Handler
const servicesDropdown = document.getElementById("servicesDropdown");
const dropbtn = servicesDropdown ? servicesDropdown.querySelector(".dropbtn") : null;

if (servicesDropdown && dropbtn) {
  dropbtn.addEventListener("click", (e) => {
    if (window.innerWidth <= 900) {
      e.preventDefault();
      const isOpen = servicesDropdown.classList.toggle("active");
      dropbtn.setAttribute("aria-expanded", isOpen ? "true" : "false");
    }
  });
}

// Scroll animations
const observer = new IntersectionObserver((entries) => {
  entries.forEach((e, i) => {
    if (e.isIntersecting) {
      setTimeout(() => e.target.classList.add("visible"), i * 80);
      observer.unobserve(e.target);
    }
  });
}, { threshold: 0.1 });
document.querySelectorAll(".fade-in").forEach(el => observer.observe(el));

// Contact form AJAX handler
async function sendInquiry(e) {
  if (e) e.preventDefault();

  const form = document.getElementById("contactForm");
  const btn = document.getElementById("submitBtn");
  const btnText = document.getElementById("btnText");
  const resp = document.getElementById("formResponse");

  const full_name = document.getElementById("full_name").value.trim();
  const email     = document.getElementById("email").value.trim();
  const subject   = document.getElementById("subject").value.trim();
  const message   = document.getElementById("message").value.trim();

  // Client-side validation
  if (!full_name || !email || !subject || !message) {
    resp.className = "form-response error";
    resp.style.display = "block";
    resp.textContent = "Please fill in all required fields.";
    return;
  }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    resp.className = "form-response error";
    resp.style.display = "block";
    resp.textContent = "Please enter a valid email address.";
    return;
  }

  btn.disabled = true;
  if (btnText) btnText.textContent = "Sending...";
  resp.style.display = "none";

  try {
    const formData = new FormData(form);
    const res = await fetch("contact.php", {
      method: "POST",
      body: formData
    });
    const text = await res.text();
    resp.style.display = "block";
    if (text.includes("successfully")) {
      resp.className = "form-response success";
      resp.textContent = text;
      form.reset();
    } else {
      resp.className = "form-response error";
      resp.textContent = text || "An error occurred while sending your message.";
    }
  } catch (err) {
    resp.className = "form-response error";
    resp.style.display = "block";
    resp.textContent = "Network error. Please try again or email us directly at info@abpoafrica.com";
  } finally {
    btn.disabled = false;
    if (btnText) btnText.textContent = "Send Message";
  }
}

// Hook up event listeners
document.addEventListener("DOMContentLoaded", () => {
  const contactForm = document.getElementById("contactForm");
  if (contactForm) {
    contactForm.addEventListener("submit", sendInquiry);
  }
});
</script>

